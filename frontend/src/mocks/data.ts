export function chatToListItem(chat: Chat): ChatListItem {
  const messages = mockMessages[chat.id] ?? []
  const last = messages.length ? messages[messages.length - 1] : null
  return {
    id: chat.id,
    name: chat.name,
    model_name: chat.model_name,
    thinking_mode: chat.thinking_mode,
    last_message: last ? last.content : null,
    last_message_at: last ? last.timestamp : null,
    created_at: chat.created_at,
  }
}
